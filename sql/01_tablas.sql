/* ====== TABLAS ====== */
CREATE DATABASE Sistema_de_Gestion_Salud_Clinica_Samuel;

USE Sistema_de_Gestion_Salud_Clinica_Samuel;
go;

-- COBERTURAS --
CREATE TABLE COBERTURAS (
    COB_CODIGO INT IDENTITY(1,1) PRIMARY KEY,
    COB_NOMBRE VARCHAR(25),
    COB_PLAN VARCHAR(25),
    COB_PAGO_CONSULTA INT
);

-- PACIENTES --
CREATE TABLE PACIENTES (
    PAC_CODIGO INT IDENTITY(1,1) PRIMARY KEY,
    PAC_CUIT CHAR(11) NOT NULL,
    PAC_NOMBRE VARCHAR(25),
    PAC_APELLIDO VARCHAR(25),
    PAC_FECHA_NACIMIENTO DATE,
    PAC_DIRECCION VARCHAR(100),
    PAC_TELEFONO VARCHAR(20) NOT NULL, 
    PAC_EMAIL VARCHAR(100),
    COD_COBERTURA INT, 
    PAC_OBSERVACION  VARCHAR(150), 
    CONSTRAINT CHK_PAC_FECHA_NACIMIENTO CHECK (PAC_FECHA_NACIMIENTO <= DATEADD(YEAR, -18, GETDATE())), -- SOLO PUEDEN ATENDERSE PACIENTES A PARTIR DE 18 AÑOS, NO ES UNA CLINICA PEDIATRICA, SOLO ADULTOS.
    CONSTRAINT CHK_PAC_EMAIL CHECK (PAC_EMAIL LIKE '%@%'),
    CONSTRAINT FK_COBERTURAS FOREIGN KEY (COD_COBERTURA) REFERENCES COBERTURAS(COB_CODIGO)
);

-- ESPECIALIDADES --
CREATE TABLE ESPECIALIDADES (
    ESP_CODIGO INT IDENTITY(1,1) PRIMARY KEY,
    ESP_NOMBRE VARCHAR(50) NOT NULL, 
    ESP_OBSERVACIONES VARCHAR(20) NULL DEFAULT NULL
);

-- CONSULTORIOS --
CREATE TABLE CONSULTORIOS (
    CONS_CODIGO INT IDENTITY(1,1) PRIMARY KEY,
    CONS_OBSERVACIONES VARCHAR(20) NULL DEFAULT NULL,
    COD_ESPECIALIDAD INT,
    CONSTRAINT FK_CONS_ESPECIALIDAD FOREIGN KEY (COD_ESPECIALIDAD) REFERENCES ESPECIALIDADES(ESP_CODIGO)
);

-- PROFESIONALES --
CREATE TABLE PROFESIONALES (
    PRO_CODIGO INT IDENTITY(1,1) PRIMARY KEY,
    PRO_CUIT CHAR(11) NOT NULL,
    PRO_NOMBRE VARCHAR(25),
    PRO_APELLIDO VARCHAR(25) NOT NULL,
    PRO_FECHA_NACIMIENTO DATE,
    PRO_DIRECCION VARCHAR(100),
    PRO_TELEFONO VARCHAR(20) NOT NULL, 
    PRO_EMAIL VARCHAR(100),
    PRO_ESPECIALIDAD INT, 
    PRO_OBSERVACION VARCHAR(150),
    CONSTRAINT CHK_PRO_EMAIL CHECK (PRO_EMAIL LIKE '%@%'),
    CONSTRAINT FK_ESPECIALIDAD FOREIGN KEY (PRO_ESPECIALIDAD) REFERENCES ESPECIALIDADES(ESP_CODIGO)
);

-- ESTUDIOS --
CREATE TABLE ESTUDIOS (
    EST_CODIGO INT IDENTITY(1,1) PRIMARY KEY,
    EST_NOMBRE VARCHAR(50) NOT NULL,
    EST_DESCRIPCION VARCHAR(150) NOT NULL,
    EST_PRECIO_BASE DECIMAL(10,2) NOT NULL CHECK (EST_PRECIO_BASE >= 0)
);
 
-- DEPARTAMENTOS --
CREATE TABLE DEPARTAMENTOS (
    DEPTO_CODIGO INT IDENTITY(1,1) PRIMARY KEY,
    DEPTO_ESPECIALIDAD INT NOT NULL,
    DEPTO_NOMBRE VARCHAR(50) NOT NULL,
    DEPTO_UBICACION_PISO INT NOT NULL,
    CONSTRAINT FK_DEPTO_ESPECIALIDAD FOREIGN KEY (DEPTO_ESPECIALIDAD) REFERENCES ESPECIALIDADES(ESP_CODIGO)
);
 
-- TURNOS --
CREATE TABLE TURNOS (
    TUR_CODIGO INT IDENTITY(1,1) PRIMARY KEY,
    TUR_PACIENTE INT NOT NULL,
    TUR_PROFESIONAL INT NULL,   -- el NULL permitido solo si el turno es de tipo ESTUDIO
    TUR_CONSULTORIO INT NOT NULL,
    TUR_FECHA DATE NOT NULL,
    TUR_HORA TIME(0) NOT NULL,
    TUR_ESTADO VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    TUR_TIPO_TURNO VARCHAR(20) NOT NULL,
    CONSTRAINT CHK_TUR_ESTADO CHECK (TUR_ESTADO IN ('PENDIENTE', 'CONFIRMADO', 'FINALIZADO', 'CANCELADO', 'AUSENTE')),
    CONSTRAINT CHK_TUR_TIPO_TURNO CHECK (TUR_TIPO_TURNO IN ('CONSULTA', 'ESTUDIO')),
    CONSTRAINT CHK_TUR_PROFESIONAL_SEGUN_TIPO CHECK (TUR_TIPO_TURNO = 'ESTUDIO' OR TUR_PROFESIONAL IS NOT NULL),
    CONSTRAINT FK_TUR_PACIENTE FOREIGN KEY (TUR_PACIENTE) REFERENCES PACIENTES(PAC_CODIGO),
    CONSTRAINT FK_TUR_PROFESIONAL FOREIGN KEY (TUR_PROFESIONAL) REFERENCES PROFESIONALES(PRO_CODIGO),
    CONSTRAINT FK_TUR_CONSULTORIO FOREIGN KEY (TUR_CONSULTORIO) REFERENCES CONSULTORIOS(CONS_CODIGO),
    CONSTRAINT UQ_TUR_CONSULTORIO_FECHA_HORA UNIQUE (TUR_CONSULTORIO, TUR_FECHA, TUR_HORA)
);
 
-- ATENCIONES_MEDICAS --
CREATE TABLE ATENCIONES_MEDICAS (
    AM_CODIGO INT IDENTITY(1,1) PRIMARY KEY,
    AM_TURNO INT NOT NULL,
    AM_MOTIVO_CONSULTA VARCHAR(150),
    AM_DIAGNOSTICO VARCHAR(250),
    AM_OBSERVACIONES VARCHAR(250),
    CONSTRAINT UQ_AM_TURNO UNIQUE (AM_TURNO),
    CONSTRAINT FK_AM_TURNO FOREIGN KEY (AM_TURNO) REFERENCES TURNOS(TUR_CODIGO)
);

-- ESTUDIOS_SOLICITADOS -- 
CREATE TABLE ESTUDIOS_SOLICITADOS (
    ESO_CODIGO INT IDENTITY(1,1) PRIMARY KEY,
    ESO_ATENCION INT NOT NULL,
    ESO_ESTUDIO INT NOT NULL,
    ESO_ESTADO VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    ESO_TURNO INT NULL, -- Se completa al programar el estudio
    ESO_DEPARTAMENTO INT NULL,
    CONSTRAINT CHK_ESO_ESTADO CHECK (ESO_ESTADO IN ('PENDIENTE', 'PROGRAMADO', 'REALIZADO', 'CANCELADO')),
    CONSTRAINT FK_ESO_ATENCION FOREIGN KEY (ESO_ATENCION) REFERENCES ATENCIONES_MEDICAS(AM_CODIGO),
    CONSTRAINT FK_ESO_ESTUDIO FOREIGN KEY (ESO_ESTUDIO) REFERENCES ESTUDIOS(EST_CODIGO),
    CONSTRAINT FK_ESO_TURNO FOREIGN KEY (ESO_TURNO) REFERENCES TURNOS(TUR_CODIGO),
    CONSTRAINT FK_ESO_DEPARTAMENTO FOREIGN KEY (ESO_DEPARTAMENTO) REFERENCES DEPARTAMENTOS(DEPTO_CODIGO)
);
 
-- FACTURACIONES --
CREATE TABLE FACTURACIONES (
    FACT_CODIGO INT IDENTITY(1,1) PRIMARY KEY,
    FACT_ATENCION INT NOT NULL,
    FACT_FECHA DATE NOT NULL DEFAULT CAST(GETDATE() AS DATE),
    FACT_HORA TIME(0) NOT NULL DEFAULT CAST(GETDATE() AS TIME(0)),
    FACT_MONTO_TOTAL DECIMAL(10,2) NOT NULL CHECK (F_MONTO_TOTAL >= 0),
    FACT_MEDIO_PAGO VARCHAR(20) NOT NULL,
    FACT_ESTADO_PAGO VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    CONSTRAINT UQ_FACT_ATENCION UNIQUE (FACT_ATENCION),
    CONSTRAINT CHK_FACT_MEDIO_PAGO CHECK (FACT_MEDIO_PAGO IN ('EFECTIVO', 'DEBITO', 'CREDITO', 'TRANSFERENCIA')),
    CONSTRAINT CHK_FACT_ESTADO_PAGO CHECK (FACT_ESTADO_PAGO IN ('PENDIENTE', 'APROBADO', 'RECHAZADO', 'ANULADO')),
    CONSTRAINT FK_FACT_ATENCION FOREIGN KEY (FACT_ATENCION) REFERENCES ATENCIONES_MEDICAS(AM_CODIGO)
);
 
-- DETALLES_FACTURAS --
CREATE TABLE DETALLES_FACTURAS (
    DF_CODIGO INT IDENTITY(1,1) PRIMARY KEY,
    DF_FACTURA INT NOT NULL,
    DF_ESTUDIO_SOLICITADO INT NOT NULL,
    DF_PRECIO_APLICADO DECIMAL(10,2) NOT NULL CHECK (DF_PRECIO_APLICADO >= 0),
    DF_MONTO_COBERTURA DECIMAL(10,2) NOT NULL CHECK (DF_MONTO_COBERTURA >= 0),
    DF_MONTO_PACIENTE DECIMAL(10,2) NOT NULL CHECK (DF_MONTO_PACIENTE >= 0),
    CONSTRAINT FK_DF_FACTURA FOREIGN KEY (DF_FACTURA) REFERENCES FACTURACIONES(FACT_CODIGO),
    CONSTRAINT FK_DF_ESTUDIO_SOLICITADO FOREIGN KEY (DF_ESTUDIO_SOLICITADO) REFERENCES ESTUDIOS_SOLICITADOS(ESO_CODIGO),
    CONSTRAINT CHK_DF_MONTOS CHECK (DF_MONTO_COBERTURA + DF_MONTO_PACIENTE = DF_PRECIO_APLICADO)
);
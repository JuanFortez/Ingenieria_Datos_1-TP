/* ====== VIEWS ====== */
USE Sistema_de_Gestion_Salud_Clinica_Samuel;
GO

CREATE VIEW vw_pacientes AS
SELECT *
FROM PACIENTES;
GO

CREATE VIEW vw_pacientes_por_cobertura AS
SELECT
    C.COB_NOMBRE AS obra_social,
    C.COB_PLAN AS plan_cobertura,
    COUNT(P.PAC_CODIGO) AS cantidad_pacientes
FROM COBERTURAS C
LEFT JOIN PACIENTES P ON P.COD_COBERTURA = C.COB_CODIGO
GROUP BY C.COB_CODIGO, C.COB_NOMBRE, C.COB_PLAN;
GO

CREATE VIEW vw_pacientes_sin_atenciones AS
SELECT
    P.PAC_CUIT AS cuit_paciente,
    CONCAT(P.PAC_NOMBRE, ' ', P.PAC_APELLIDO) AS nombre_paciente
FROM PACIENTES P
WHERE NOT EXISTS (
    SELECT *
    FROM TURNOS T
    INNER JOIN ATENCIONES_MEDICAS A ON A.AM_TURNO = T.TUR_CODIGO
    WHERE T.TUR_PACIENTE = P.PAC_CODIGO
);
GO

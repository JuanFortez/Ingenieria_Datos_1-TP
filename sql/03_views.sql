/* ====== VIEWS ====== */
USE Sistema_de_Gestion_Salud_Clinica_Samuel;
GO

CREATE VIEW vw_pacientes AS
SELECT *
FROM PACIENTES;
GO

CREATE VIEW vw_pacientes_por_cobertura AS
SELECT
    C.COB_NOMBRE AS obra_social,
    PL.PLAN_NOMBRE AS plan_cobertura,
    COUNT(P.PAC_CODIGO) AS cantidad_pacientes
FROM COBERTURAS C
INNER JOIN PLANES PL ON PL.PLAN_COBERTURA = C.COB_CODIGO
LEFT JOIN PACIENTES P ON P.COD_PLAN = PL.PLAN_CODIGO
GROUP BY C.COB_CODIGO, C.COB_NOMBRE, PL.PLAN_CODIGO, PL.PLAN_NOMBRE;
GO

CREATE VIEW vw_pacientes_sin_atenciones AS
SELECT
    P.PAC_CUIT AS cuit_paciente,
    CONCAT(P.PAC_NOMBRE, ' ', P.PAC_APELLIDO) AS nombre_paciente
FROM PACIENTES P
WHERE NOT EXISTS (
    SELECT *
    FROM TURNOS T
    INNER JOIN ATENCIONES_MEDICAS A ON A.AM_TURNO = T.TUR_CODIGO
    WHERE T.TUR_PACIENTE = P.PAC_CODIGO
);
GO

CREATE VIEW vw_estudios_solicitados AS
SELECT
    ESO.ESO_CODIGO,
    ESO.ESO_ATENCION,
    ESO.ESO_ESTUDIO,
    E.EST_NOMBRE,
    ESO.ESO_ESTADO AS ESTADO,
    ESO.ESO_TURNO,
    P.PRO_CODIGO,
    P.PRO_NOMBRE + ' ' + P.PRO_APELLIDO AS PROFESIONAL,
    ESP.ESP_NOMBRE AS ESPECIALIDAD,
    D.DEPTO_CODIGO,
    D.DEPTO_NOMBRE AS DEPARTAMENTO
FROM ESTUDIOS_SOLICITADOS ESO
INNER JOIN ESTUDIOS E ON E.EST_CODIGO = ESO.ESO_ESTUDIO
INNER JOIN ATENCIONES_MEDICAS AM ON AM.AM_CODIGO = ESO.ESO_ATENCION
INNER JOIN TURNOS T ON T.TUR_CODIGO = AM.AM_TURNO
LEFT JOIN PROFESIONALES P ON P.PRO_CODIGO = T.TUR_PROFESIONAL
LEFT JOIN ESPECIALIDADES ESP ON ESP.ESP_CODIGO = P.PRO_ESPECIALIDAD
LEFT JOIN DEPARTAMENTOS D ON D.DEPTO_ESPECIALIDAD = P.PRO_ESPECIALIDAD;
GO

CREATE VIEW CANTIDAD_CONSULTAS_PACIENTES
-- Esta View cuenta la cantidad de TODAS las consultas realizadas por paciente en la clinica...
AS
SELECT
    TUR_PACIENTE,
    COUNT(*) AS CANTIDAD_CONSULTAS
FROM TURNOS
WHERE TUR_TIPO_TURNO = 'CONSULTA'
GROUP BY TUR_PACIENTE;
GO


CREATE VIEW CANTIDAD_CONSULTAS_PACIENTES_POR_MES
-- Esta VIEW cuenta la cantidad de consultas realizadas por paciente en un MES determinado.
AS
SELECT
    TUR_PACIENTE,
    COUNT(*) AS CANTIDAD_CONSULTAS
FROM TURNOS
WHERE TUR_TIPO_TURNO = 'CONSULTA'
AND TUR_FECHA BETWEEN '20261001' AND '20261031'
GROUP BY TUR_PACIENTE;
GO



CREATE VIEW INGRESO_POR_PACIENTE_POR_MES
-- Esta VIEW muestra el INGRESO realizado por paciente en un mes determinado.
-- (Se multiplica la cantidad de consultas de pacientes de una obra social por un valor determinado). 
AS
SELECT
    PACIENTES.PAC_CODIGO,
    PACIENTES.PAC_APELLIDO,
    COUNT(*) AS CANTIDAD_CONSULTAS,
    PLANES.PLAN_PAGO_CONSULTA,
    COUNT(*) * PLANES.PLAN_PAGO_CONSULTA AS INGRESO_TOTAL
FROM TURNOS

INNER JOIN PACIENTES
ON TURNOS.TUR_PACIENTE = PACIENTES.PAC_CODIGO

INNER JOIN PLANES
ON PACIENTES.COD_PLAN = PLANES.PLAN_CODIGO

WHERE TUR_FECHA BETWEEN '20261001' AND '20261031'
AND TUR_TIPO_TURNO = 'CONSULTA'

GROUP BY
    PACIENTES.PAC_CODIGO,
    PACIENTES.PAC_APELLIDO,
    PLANES.PLAN_PAGO_CONSULTA;
GO


CREATE VIEW INGRESOS_MENSUALES_POR_CONSULTAS
-- Este VIEW muestra el ingreso total generado por la CLINICA MEDICA segun los ingresos por consultas.
-- No tiene en cuenta los ingresos generados por los estudios.
AS
SELECT
    SUM(PLANES.PLAN_PAGO_CONSULTA) AS INGRESO_MENSUAL_TOTAL
FROM TURNOS

INNER JOIN PACIENTES
ON TURNOS.TUR_PACIENTE = PACIENTES.PAC_CODIGO

INNER JOIN PLANES
ON PACIENTES.COD_PLAN = PLANES.PLAN_CODIGO

WHERE TUR_FECHA BETWEEN '20261001' AND '20261031'
AND TUR_TIPO_TURNO = 'CONSULTA';
GO
